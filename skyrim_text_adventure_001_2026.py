# --- GLOBALS & UTILITIES ---
DELAY_SPEED = 0.03

def slow_print(text, delay=None):
    """Prints text with a typing effect for atmospheric storytelling."""
    actual_delay = delay if delay is not None else DELAY_SPEED
    for char in text:
        sys.stdout.write(char)
        sys.stdout.flush()
        time.sleep(actual_delay)
    print()

def clear_screen():
    """Prints spacers to keep the console clean and readable."""
    print("\n" * 3)
    print("=" * 80)
    print("\n" * 1)

# --- GAME STATE OBJECT ---
class GameState:
    def __init__(self):
        self.player_name = "Prisoner"
        self.race = "Norse"
        self.character_class = "Warrior"

        # Core Stats
        self.level = 1
        self.xp = 0
        self.xp_needed = 100
        self.hp = 100
        self.max_hp = 100
        self.mana = 50
        self.max_mana = 50

        # Combat Attributes
        self.attack_power = 15
        self.spell_power = 10
        self.defense = 5

        # Gold and Inventory
        self.gold = 50
        self.inventory = ["Sweetroll", "Healing Potion"]
        self.spells = ["Flames"]
        self.shouts = []

        # Quest / Story Flags
        self.current_location = "Helgen"
        self.main_quest_progress = 0
        self.dark_brotherhood_progress = 0
        self.winterhold_progress = 0

        # Narrative Choices
        self.joined_stormcloaks = False
        self.joined_imperials = False
        self.has_dragonstone = False
        self.killed_paarthurnax = False
        self.is_harbinger = False
        self.archmage = False
        self.void_champion = False

        # Companion state
        self.companion = None # e.g. "Lydia"

    def show_stats(self):
        print("\n" + "*" * 40)
        print(f"  CHARACTER SHEET: {self.player_name.upper()}")
        print("*" * 40)
        print(f"  Race:         {self.race}")
        print(f"  Class:        {self.character_class}")
        print(f"  Level:        {self.level}  (XP: {self.xp}/{self.xp_needed})")
        print(f"  HP:           {self.hp}/{self.max_hp}")
        print(f"  Mana:         {self.mana}/{self.max_mana}")
        print(f"  Attack/Spell: {self.attack_power} / {self.spell_power}")
        print(f"  Defense:      {self.defense}")
        print(f"  Gold:         {self.gold} Septims")
        print(f"  Inventory:    {', '.join(self.inventory) if self.inventory else 'Empty'}")
        print(f"  Spells:       {', '.join(self.spells) if self.spells else 'None'}")
        print(f"  Shouts:       {', '.join(self.shouts) if self.shouts else 'None'}")
        if self.companion:
            print(f"  Companion:    {self.companion}")
        print("*" * 40 + "\n")

    def add_xp(self, amount):
        self.xp += amount
        slow_print(f"\n[+] You gained {amount} Experience Points!")
        if self.xp >= self.xp_needed:
            self.level_up()

    def level_up(self):
        self.level += 1
        self.xp -= self.xp_needed
        self.xp_needed = int(self.xp_needed * 1.5)
        self.max_hp += 20
        self.max_mana += 15
        self.hp = self.max_hp
        self.mana = self.max_mana
        self.attack_power += 5
        self.spell_power += 4
        self.defense += 2
        slow_print("\n" + "#" * 50)
        slow_print(f" LEVEL UP! You are now Level {self.level}!")
        slow_print(" Your Health, Mana, and combat powers have been increased!")
        slow_print("#" * 50 + "\n")

    def check_alive(self):
        if self.hp <= 0:
            slow_print("\n[!] Your vision goes dark. The cold winds of Sovngarde call your name...")
            slow_print("=== GAME OVER ===")
            sys.exit(0)

